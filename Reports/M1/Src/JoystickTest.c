static uint16_t ma_buf[ADC_CH_CNT][MA_LEN];
static uint32_t ma_sum[ADC_CH_CNT];
static uint8_t  ma_idx = 0;
static uint8_t  ma_filled = 0;

static void ma_push(const uint16_t *sample, uint16_t *out)
{
	for (int c = 0; c < ADC_CH_CNT; c++) {
		ma_sum[c] -= ma_buf[c][ma_idx];
		ma_buf[c][ma_idx] = sample[c];
		ma_sum[c] += sample[c];
		out[c] = (uint16_t)(ma_sum[c]/MA_LEN);
	}
	ma_idx = (ma_idx + 1) % MA_LEN;
	if (ma_idx == 0) ma_filled = 1;
}

static void adc_noise_report(void)
{
	uint16_t mn[ADC_CH_CNT] = {0xFFFF, 0xFFFF};
	uint16_t mx[ADC_CH_CNT] = {0, 0};
	uint32_t sum[ADC_CH_CNT] = {0, 0};
	const uint32_t N = 1000;

	printf("Measurement start: Take your hand off (1sec)\r\n");
	HAL_Delay(500);

	for (uint32_t i = 0; i < N; i++) {
		for (int c = 0; c < ADC_CH_CNT; c++) {
			uint16_t v = g_adc_raw[c];
			if (v < mn[c]) mn[c] = v;
			if (v > mx[c]) mx[c] = v;
			sum[c] += v;
		}
		HAL_Delay(1);
	}
	for (int c = 0; c < ADC_CH_CNT; c++) {
		printf("CH%d  min=%4u  max=%4u  avg=%4lu  p-p=%3u\r\n",
				c, mn[c], mx[c], sum[c] / N, (uint16_t)(mx[c] - mn[c]));
	}
}
